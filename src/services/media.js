// Media library: validated image uploads stored on disk with random names.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import multer from 'multer';
import { all, get, run, now } from '../db/index.js';
import { config } from '../config.js';
import { AppError } from '../lib/errors.js';
import { clean } from '../lib/escape.js';

/** mime → canonical extension. SVG is intentionally not allowed (scriptable). */
export const ALLOWED_TYPES = {
  'image/jpeg': 'jpg',
  'image/png': 'png',
  'image/webp': 'webp',
  'image/gif': 'gif',
  'image/avif': 'avif',
};
export const ACCEPT_ATTR = Object.keys(ALLOWED_TYPES).join(',');
export const URL_PREFIX = '/uploads';

fs.mkdirSync(config.uploads.dir, { recursive: true });

const storage = multer.diskStorage({
  destination: (req, file, cb) => cb(null, config.uploads.dir),
  filename: (req, file, cb) => cb(null, `${crypto.randomBytes(12).toString('hex')}.${ALLOWED_TYPES[file.mimetype] || 'bin'}`),
});

/**
 * Configured multer instance. Usage in a route (multipart forms need the CSRF token in the
 * query string or X-CSRF-Token header — see lib/csrf.js):
 *   router.post('/media', media.upload.array('files', 10), handler)
 *   router.post('/products/:id', media.upload.single('image'), handler)
 * Then call registerUpload(req.file) for every file.
 */
export const upload = multer({
  storage,
  limits: { fileSize: config.uploads.maxBytes, files: 10, fields: 200, fieldSize: 2 * 1024 * 1024 },
  fileFilter: (req, file, cb) => {
    if (!ALLOWED_TYPES[file.mimetype]) {
      return cb(new AppError('bad_file_type', 'Можно загружать только изображения JPG, PNG, WebP, GIF или AVIF', 415));
    }
    return cb(null, true);
  },
});

function sniff(file) {
  const fd = fs.openSync(file, 'r');
  try {
    const buf = Buffer.alloc(16);
    fs.readSync(fd, buf, 0, 16, 0);
    if (buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return 'image/jpeg';
    if (buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))) return 'image/png';
    if (buf.toString('latin1', 0, 4) === 'GIF8') return 'image/gif';
    if (buf.toString('latin1', 0, 4) === 'RIFF' && buf.toString('latin1', 8, 12) === 'WEBP') return 'image/webp';
    if (buf.toString('latin1', 4, 8) === 'ftyp' && /^avi[fs]/.test(buf.toString('latin1', 8, 12))) return 'image/avif';
    return null;
  } finally {
    fs.closeSync(fd);
  }
}

const safeUnlink = (file) => {
  try {
    fs.unlinkSync(file);
  } catch { /* already gone */ }
};

/**
 * Validate a multer file by its magic bytes and add it to the library.
 * Invalid files are deleted from disk and an AppError('bad_file_type') is thrown.
 * @param {Express.Multer.File} file
 * @param {{ adminId?: number, alt?: string }} [meta]
 * @returns {{ id, filename, original_name, mime, size, url, alt, created_at }}
 */
export function registerUpload(file, { adminId = null, alt = '' } = {}) {
  if (!file || !file.path) throw new AppError('validation', 'Файл не выбран', 422);
  const real = sniff(file.path);
  if (!real || real !== file.mimetype) {
    safeUnlink(file.path);
    throw new AppError('bad_file_type', 'Файл не похож на изображение. Допустимы JPG, PNG, WebP, GIF, AVIF', 415);
  }
  const url = `${URL_PREFIX}/${file.filename}`;
  const original = clean(Buffer.from(file.originalname || '', 'latin1').toString('utf8'), 200);
  const { lastInsertRowid } = run(
    'INSERT INTO media (filename, original_name, mime, size, url, alt, uploaded_by, created_at) VALUES (?, ?, ?, ?, ?, ?, ?, ?)',
    file.filename, original, real, file.size, url, clean(alt, 200), adminId, now(),
  );
  return getMedia(Number(lastInsertRowid));
}

/** Discard files multer saved for a request that failed validation later. */
export function discardUploads(files) {
  for (const f of [].concat(files || [])) if (f?.path) safeUnlink(f.path);
}

export function getMedia(id) {
  return get('SELECT * FROM media WHERE id = ?', Number(id));
}

/** Newest first. @returns {{ items: object[], total: number }} */
export function listMedia({ limit = 60, offset = 0 } = {}) {
  return {
    items: all('SELECT * FROM media ORDER BY id DESC LIMIT ? OFFSET ?', Number(limit), Number(offset)),
    total: get('SELECT COUNT(*) AS n FROM media').n,
  };
}

export function updateMedia(id, { alt = '' } = {}) {
  run('UPDATE media SET alt = ? WHERE id = ?', clean(alt, 200), Number(id));
  return getMedia(id);
}

/** Delete the DB row and the file. Returns false when the id is unknown. */
export function deleteMedia(id) {
  const row = getMedia(id);
  if (!row) return false;
  run('DELETE FROM media WHERE id = ?', row.id);
  // filename is a random hex name generated by us, never user input
  safeUnlink(path.join(config.uploads.dir, path.basename(row.filename)));
  return true;
}

/** Russian message for upload errors (multer + ours). */
export function uploadErrorMessage(err) {
  if (err instanceof multer.MulterError) {
    if (err.code === 'LIMIT_FILE_SIZE') return `Файл слишком большой. Максимум — ${Math.round(config.uploads.maxBytes / 1024 / 1024)} МБ`;
    if (err.code === 'LIMIT_FILE_COUNT' || err.code === 'LIMIT_UNEXPECTED_FILE') return 'Слишком много файлов за один раз';
    return 'Не удалось загрузить файл';
  }
  return err?.expose ? err.message : 'Не удалось загрузить файл';
}
